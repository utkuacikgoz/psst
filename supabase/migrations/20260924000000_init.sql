-- Psst core schema.
--
-- Clients may only read through row-level security (RLS) and write through the
-- functions below. Every function derives the caller from auth.uid(); no function
-- accepts a user ID for "who am I". Errors use PostgREST's PTxxx codes, so they
-- reach the client as HTTP status xxx with a machine-readable message.

create schema if not exists private;
revoke all on schema private from public;

-- Effects ---------------------------------------------------------------------

create table public.effects (
    id text primary key,
    title text not null,
    is_free boolean not null default true,
    sort_order int not null
);

